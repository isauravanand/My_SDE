from functools import lru_cache
from typing import Literal

from pydantic import Field, field_validator, model_validator
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        extra="ignore",
        case_sensitive=False,
    )

    # Core Application
    APP_NAME: str = Field(default="MySDE Backend", description="Application display name")
    APP_ENV: Literal["development", "staging", "production", "test"] = Field(
        default="development", description="Runtime environment"
    )
    DEBUG: bool = Field(default=False, description="Enable debug mode")
    LOG_LEVEL: str = Field(default="INFO", description="Log level (DEBUG, INFO, WARNING, ERROR)")
    API_V1_PREFIX: str = Field(default="/api/v1", description="Prefix for API v1 routes")
    FRONTEND_URL: str = Field(default="http://localhost:5173", description="Frontend origin URL")

    # Security & Sessions
    SECRET_KEY: str = Field(
        default="development-insecure-secret-key-replace-in-production-min32chars",
        description="Secret key used for cryptographic signatures",
    )
    SESSION_MAX_AGE_DAYS: int = Field(default=7, ge=1, le=90)
    COOKIE_SECURE: bool = Field(
        default=False,
        description="Set Secure flag on cookies. Enforced True in production.",
    )
    COOKIE_SAMESITE: Literal["lax", "strict", "none"] = Field(default="lax")

    # GitHub App Integration
    GITHUB_APP_ID: str | None = Field(default=None, description="GitHub App ID")
    GITHUB_APP_CLIENT_ID: str | None = Field(default=None, description="GitHub App Client ID")
    GITHUB_APP_CLIENT_SECRET: str | None = Field(default=None, description="GitHub App Client Secret")
    GITHUB_APP_PRIVATE_KEY_PATH: str | None = Field(
        default=None, description="Path to PEM private key file"
    )
    GITHUB_APP_PRIVATE_KEY: str | None = Field(
        default=None, description="Raw PEM private key string (alternative to path)"
    )
    GITHUB_WEBHOOK_SECRET: str | None = Field(default=None, description="GitHub Webhook Secret")
    GITHUB_CALLBACK_URL: str | None = Field(
        default=None, description="Callback URL for GitHub App installation redirect"
    )
    GITHUB_APP_SLUG: str | None = Field(
        default=None, description="GitHub App slug for direct installation URLs"
    )

    @property
    def is_github_configured(self) -> bool:
        """Return True if GitHub App integration is fully configured."""
        has_key = bool(self.GITHUB_APP_PRIVATE_KEY or self.GITHUB_APP_PRIVATE_KEY_PATH)
        return bool(self.GITHUB_APP_ID and self.GITHUB_APP_CLIENT_ID and has_key)

    # Code RAG & Embedding Provider Settings
    EMBEDDING_PROVIDER: Literal["fake", "openai", "local"] = Field(
        default="fake",
        description="Embedding provider to use: 'fake' for offline/testing, 'openai' for OpenAI/compatible API, or 'local'",
    )
    EMBEDDING_MODEL: str = Field(
        default="mock-embed-384",
        description="Embedding model identifier (e.g. mock-embed-384, text-embedding-3-small)",
    )
    EMBEDDING_DIMENSIONS: int = Field(
        default=384,
        description="Dimension size of embeddings generated by the configured model",
    )
    EMBEDDING_API_KEY: str | None = Field(
        default=None,
        description="API key for embedding provider (e.g. OpenAI or compatible)",
    )
    EMBEDDING_BASE_URL: str | None = Field(
        default=None,
        description="Optional base URL for OpenAI-compatible embedding servers",
    )
    CODE_RAG_MAX_FILE_SIZE_BYTES: int = Field(
        default=512 * 1024,  # 512 KB
        description="Maximum file size in bytes to index into Code RAG",
    )
    CODE_RAG_MAX_FILES_PER_REPO: int = Field(
        default=1000,
        description="Maximum number of files to index per repository run",
    )
    CODE_RAG_CHUNK_SIZE_LINES: int = Field(
        default=60,
        description="Target lines per chunk for line-based chunking fallback",
    )
    CODE_RAG_CHUNK_OVERLAP_LINES: int = Field(
        default=12,
        description="Overlap lines between sequential chunks",
    )

    @property
    def is_embedding_configured(self) -> bool:
        """Return True if a real embedding provider is configured with credentials."""
        if self.EMBEDDING_PROVIDER == "openai":
            return bool(self.EMBEDDING_API_KEY)
        return self.EMBEDDING_PROVIDER != "fake"

    # LLM & Planning Agent Settings (Phase 6)
    LLM_PROVIDER: Literal["mock", "openai", "anthropic", "gemini", "groq"] = Field(
        default="mock",
        description="LLM provider for implementation planning: 'mock' for offline testing, 'openai', 'anthropic', 'gemini', or 'groq'",
    )
    LLM_MODEL: str = Field(
        default="gpt-4o-mini",
        description="LLM model identifier for planning (e.g. gpt-4o-mini, gpt-4o, claude-3-5-sonnet)",
    )
    LLM_API_KEY: str | None = Field(
        default=None,
        description="API key for LLM provider (e.g. OpenAI or compatible)",
    )
    LLM_BASE_URL: str | None = Field(
        default=None,
        description="Optional base URL for OpenAI-compatible LLM endpoints",
    )
    PLANNING_TEMPERATURE: float = Field(
        default=0.2,
        ge=0.0,
        le=1.0,
        description="Sampling temperature for planning generation",
    )
    PLANNING_MAX_OUTPUT_TOKENS: int = Field(
        default=4096,
        ge=512,
        le=16384,
        description="Maximum token output limit for generated implementation plans",
    )
    PLANNING_MAX_RETRIES: int = Field(
        default=2,
        ge=0,
        le=5,
        description="Maximum model retry attempts for structured schema validation repair",
    )
    PLANNING_TOP_K_CHUNKS: int = Field(
        default=8,
        ge=1,
        le=20,
        description="Number of relevant Code RAG chunks retrieved into planning context",
    )

    @property
    def is_llm_configured(self) -> bool:
        """Return True if LLM provider has valid credentials or runs in mock mode."""
        if self.LLM_PROVIDER == "mock":
            return True
        return bool(self.LLM_API_KEY)

    # Isolated Execution & Sandbox Settings (Phase 7)
    SANDBOX_PROVIDER: Literal["docker", "mock"] = Field(
        default="docker",
        description="Sandbox execution provider: 'docker' for isolated container execution, 'mock' for simulated safe testing",
    )
    SANDBOX_DOCKER_IMAGE: str = Field(
        default="python:3.10-slim",
        description="Controlled base container image for isolated execution sandbox",
    )
    SANDBOX_TIMEOUT_SECONDS: int = Field(
        default=60,
        ge=5,
        le=300,
        description="Maximum execution timeout in seconds for verification commands",
    )
    SANDBOX_MEMORY_LIMIT: str = Field(
        default="1024m",
        description="Memory limit for Docker sandbox container (e.g. 512m, 1024m)",
    )
    SANDBOX_CPU_LIMIT: float = Field(
        default=1.0,
        ge=0.1,
        le=4.0,
        description="CPU limit for Docker sandbox container",
    )
    SANDBOX_MAX_OUTPUT_BYTES: int = Field(
        default=20480,
        ge=1024,
        le=1048576,
        description="Maximum bounded stdout/stderr capture in bytes per command (20 KB default)",
    )
    SANDBOX_MAX_PATCH_BYTES: int = Field(
        default=512000,
        ge=1024,
        le=5242880,
        description="Maximum allowable unified diff patch size in bytes (500 KB default)",
    )
    SANDBOX_MAX_PATCH_FILES: int = Field(
        default=20,
        ge=1,
        le=100,
        description="Maximum allowable changed files in a single patch proposal",
    )

    # Bounded AI Repair Loop Settings (Phase 8)
    REPAIR_MAX_ATTEMPTS: int = Field(
        default=3,
        ge=1,
        le=10,
        description="Maximum automated repair loop attempts per execution run",
    )
    REPAIR_MAX_DURATION_SECONDS: int = Field(
        default=600,
        ge=60,
        le=3600,
        description="Maximum total duration in seconds for repair run (10 minutes default)",
    )
    REPAIR_MAX_MODEL_CALLS: int = Field(
        default=6,
        ge=1,
        le=20,
        description="Maximum LLM API calls allowed across repair attempts",
    )

    # Email Service
    EMAIL_PROVIDER: Literal["development", "smtp", "console"] = Field(
        default="development",
        description="Email service provider. Defaults to development adapter.",
    )
    EMAIL_FROM: str = Field(default="noreply@mysde.local")
    SMTP_HOST: str | None = None
    SMTP_PORT: int = 587
    SMTP_USER: str | None = None
    SMTP_PASSWORD: str | None = None

    # Billing & Subscription Settings (Phase 11)
    BILLING_PROVIDER: Literal["mock", "razorpay"] = Field(
        default="mock",
        description="Payment and billing provider: 'mock' for zero-credential local testing, 'razorpay' for India-compatible gateway",
    )
    RAZORPAY_KEY_ID: str | None = Field(
        default=None,
        description="Razorpay API Key ID (e.g. rzp_test_...)",
    )
    RAZORPAY_KEY_SECRET: str | None = Field(
        default=None,
        description="Razorpay API Key Secret",
    )
    RAZORPAY_WEBHOOK_SECRET: str | None = Field(
        default=None,
        description="HMAC secret for verifying inbound Razorpay webhook events",
    )
    BILLING_ENFORCEMENT_ENABLED: bool = Field(
        default=True,
        description="Enforce server-side usage quotas and subscription limits",
    )

    @property
    def is_razorpay_configured(self) -> bool:
        """Return True if Razorpay credentials are fully configured."""
        return bool(self.RAZORPAY_KEY_ID and self.RAZORPAY_KEY_SECRET)

    # Database
    DATABASE_URL: str = Field(
        default="postgresql+psycopg://postgres:postgres@localhost:5432/mysde_dev",
        description="SQLAlchemy database connection URI",
    )
    DB_POOL_SIZE: int = Field(default=10, ge=1, le=50)
    DB_MAX_OVERFLOW: int = Field(default=10, ge=0, le=50)
    DB_POOL_PRE_PING: bool = Field(default=True)
    DB_POOL_TIMEOUT: int = Field(default=10, ge=1, le=60)

    # CORS
    CORS_ORIGINS: list[str] | str = Field(
        default_factory=lambda: ["http://localhost:5173", "http://localhost:3000"]
    )

    @field_validator("CORS_ORIGINS", mode="before")
    @classmethod
    def parse_cors_origins(cls, value: str | list[str]) -> list[str]:
        if isinstance(value, str):
            origins = [
                origin.strip().rstrip("/")
                for origin in value.split(",")
                if origin.strip()
            ]
            return origins
        if isinstance(value, list):
            return [str(origin).strip().rstrip("/") for origin in value if str(origin).strip()]
        return ["http://localhost:5173", "http://localhost:3000"]

    @field_validator("DATABASE_URL")
    @classmethod
    def validate_database_url(cls, value: str) -> str:
        clean_val = value.strip()
        allowed_schemes = (
            "postgresql://",
            "postgresql+psycopg://",
            "postgresql+psycopg2://",
            "postgresql+asyncpg://",
            "sqlite://",
            "sqlite+aiosqlite://",
        )
        if not any(clean_val.startswith(scheme) for scheme in allowed_schemes):
            raise ValueError(
                f"DATABASE_URL must start with one of {allowed_schemes}. Got: {clean_val.split('://')[0]}://"
            )
        return clean_val

    @model_validator(mode="after")
    def validate_production_constraints(self) -> "Settings":
        if self.APP_ENV == "production":
            if len(self.SECRET_KEY) < 32:
                raise ValueError(
                    "SECRET_KEY must be at least 32 characters long in production environments"
                )
            # Enforce cookie security in production
            self.COOKIE_SECURE = True
        return self

    @field_validator("LOG_LEVEL")
    @classmethod
    def validate_log_level(cls, value: str) -> str:
        levels = {"DEBUG", "INFO", "WARNING", "ERROR", "CRITICAL"}
        val_upper = value.upper()
        if val_upper not in levels:
            raise ValueError(f"LOG_LEVEL must be one of {levels}. Got '{value}'")
        return val_upper


@lru_cache
def get_settings() -> Settings:
    """Return cached application settings loaded from environment/.env."""
    return Settings()


settings: Settings = get_settings()
