import uuid
from datetime import datetime
from typing import TYPE_CHECKING, Any

from sqlalchemy import (
    DateTime,
    ForeignKey,
    Index,
    String,
    Text,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship
from sqlalchemy.types import JSON

from app.db.base import GUID, Base, TimestampMixin, UUIDPrimaryKeyMixin

if TYPE_CHECKING:
    from app.models.github import GitHubRepository
    from app.models.task import Task
    from app.models.user import User
    from app.models.workspace import Workspace


class PlanningRun(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Tracks an orchestration run of the LangGraph planning agent for a task."""

    __tablename__ = "planning_runs"
    __table_args__ = (
        Index("ix_planning_runs_workspace_task", "workspace_id", "task_id"),
        Index("ix_planning_runs_task_status", "task_id", "status"),
    )

    workspace_id: Mapped[uuid.UUID] = mapped_column(
        GUID(),
        ForeignKey("workspaces.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    task_id: Mapped[uuid.UUID] = mapped_column(
        GUID(),
        ForeignKey("tasks.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    repository_id: Mapped[uuid.UUID | None] = mapped_column(
        GUID(),
        ForeignKey("github_repositories.id", ondelete="SET NULL"),
        index=True,
        nullable=True,
    )
    requested_by_user_id: Mapped[uuid.UUID] = mapped_column(
        GUID(),
        ForeignKey("users.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    status: Mapped[str] = mapped_column(
        String(32),
        default="queued",
        index=True,
        nullable=False,
    )  # queued, running, completed, failed, cancelled, needs_context

    base_commit_sha: Mapped[str | None] = mapped_column(String(40), nullable=True)
    model_version: Mapped[str | None] = mapped_column(String(128), nullable=True)
    prompt_version: Mapped[str | None] = mapped_column(String(64), nullable=True)
    error_summary: Mapped[str | None] = mapped_column(Text, nullable=True)

    started_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
    )
    completed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    # Relationships
    workspace: Mapped["Workspace"] = relationship("Workspace", lazy="selectin")
    task: Mapped["Task"] = relationship("Task", lazy="selectin")
    repository: Mapped["GitHubRepository | None"] = relationship("GitHubRepository", lazy="selectin")
    requested_by_user: Mapped["User"] = relationship("User", lazy="selectin")
    plan: Mapped["ImplementationPlan | None"] = relationship(
        "ImplementationPlan",
        back_populates="planning_run",
        uselist=False,
        cascade="all, delete-orphan",
        lazy="selectin",
    )


class ImplementationPlan(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Persisted structured implementation plan generated by a planning run."""

    __tablename__ = "implementation_plans"
    __table_args__ = (
        Index("ix_implementation_plans_task_created", "task_id", "created_at"),
    )

    planning_run_id: Mapped[uuid.UUID] = mapped_column(
        GUID(),
        ForeignKey("planning_runs.id", ondelete="CASCADE"),
        unique=True,
        index=True,
        nullable=False,
    )
    workspace_id: Mapped[uuid.UUID] = mapped_column(
        GUID(),
        ForeignKey("workspaces.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    task_id: Mapped[uuid.UUID] = mapped_column(
        GUID(),
        ForeignKey("tasks.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    schema_version: Mapped[str] = mapped_column(
        String(32),
        default="mysde.plan.v1",
        nullable=False,
    )
    plan_data: Mapped[dict[str, Any]] = mapped_column(
        JSON().with_variant(JSONB, "postgresql"),
        nullable=False,
    )

    # Relationships
    planning_run: Mapped["PlanningRun"] = relationship(
        "PlanningRun",
        back_populates="plan",
        lazy="selectin",
    )
    task: Mapped["Task"] = relationship("Task", lazy="selectin")
    workspace: Mapped["Workspace"] = relationship("Workspace", lazy="selectin")
